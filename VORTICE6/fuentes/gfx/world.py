"""VÓRTICE 6 · decorados ANTIC 4 (metatiles en texto), jefes y logotipo.

Píxel: '.' fondo  '1' PF0  '2' PF1  '3' PF2  '4' PF3 (carácter invertido; no se mezcla con '3' en una celda 4x8)
Cada fase: escenario de 64 columnas x 20 filas que se repite (scroll infinito del visor).
"""
import math
from canvas import C

COLS, ROWS = 64, 20
W, H = COLS * 4, ROWS * 8


def M(t):
    r = [l.strip() for l in t.strip('\n').split('\n')]
    w = max(len(l) for l in r)
    r = [l.ljust(w, '.') for l in r]
    assert w % 4 == 0 and len(r) % 8 == 0, (w, len(r), r[0])
    return r


def recolor(m, mp):
    return [''.join(mp.get(ch, ch) for ch in l) for l in m]


def vflip(m): return m[::-1]


class Scene:
    def __init__(s, cols=COLS):
        s.cols = cols
        s.w = cols * 4
        s.p = [['.'] * s.w for _ in range(H)]

    def stamp(s, m, col, row, transparent=True):
        for y, l in enumerate(m):
            for x, ch in enumerate(l):
                if transparent and ch == '.':
                    continue
                yy = row * 8 + y
                if 0 <= yy < H:
                    s.p[yy][(col * 4 + x) % s.w] = ch

    def dot(s, x, y, ch):
        s.p[y][x % s.w] = ch

    def canvas(s, c, px, py, transparent='.'):
        for y in range(c.h):
            for x in range(c.w):
                ch = c.p[y][x]
                if ch != transparent and 0 <= py + y < H:
                    s.p[py + y][(px + x) % s.w] = ch


def stars(sc, rows, seed, n=40, chars='13'):
    import random
    R = random.Random(seed)
    for _ in range(n):
        r = R.choice(rows)
        sc.dot(R.randrange(sc.w // 4) * 4 + R.choice((1, 2)), r * 8 + R.choice((2, 5)), R.choice(chars))


