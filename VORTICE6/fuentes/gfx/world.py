    """devuelve Scene de 40 columnas: VÓRTICE en metal (1/2/3) y el 6 en '4'"""
    s = Scene(40)
    x = 6
    top = 8
    for ch in 'VORTICE6':
        gl = FONT5[ch]
        if ch == '6':
            x += 4
        for gy, row in enumerate(gl):
            for gx, b in enumerate(row):
                if b != 'X':
                    continue
                for yy in range(SY):
                    for xx in range(SX):
                        Y = top + gy * SY + yy
                        if ch == '6':
                            col = '4'
                        else:
                            col = '3' if Y < top + 12 else ('2' if Y < top + 24 else '1')
                        s.p[Y][x + gx * SX + xx] = col
        if ch == 'O':   # tilde de la Ó
            for yy in range(2):
                for xx in range(4):
                    s.p[2 + yy][x + 8 + xx - yy] = '3'
        x += len(gl[0]) * SX + 3
    return s
