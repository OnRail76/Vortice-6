def boss_thalassa():
    c = C(BW, BH)
    # concha abierta
    c.ell(32, 40, 16, 38, '1')
    c.ell(32, 40, 13, 34, '2', ring='3')
    c.ell(24, 40, 10, 10, '1')
    for y in range(6, 40, 5):
        c.line(20, y + 6, 44, y, '1')
    # tentáculos hacia la izquierda
    for i, y0 in enumerate((14, 24, 34)):
        pts = [(18, y0), (12, y0 + 3), (6, y0 - 2), (1, y0 + 2)]
        for (x0, y0_), (x1, y1) in zip(pts, pts[1:]):
            c.line(x0, y0_, x1, y1, '2')
            c.line(x0, y0_ + 1, x1, y1 + 1, '1')
    # perla
    c.ell(24, 40, 8, 8, '1')
    c.ell(24, 40, 6, 6, '4')
    c.ell(22, 38, 2, 2, '.')
    return vmirror(c)


def boss_triptico():
    c = C(BW, BH)
    # altar-tótem
    c.rect(20, 0, 47, 79, '1')
    for y in range(0, 80, 8):
        c.rect(44, y, 47, y + 3, '2')
    # tres rostros apilados: Furia (arriba), Hambre (centro), Ceniza (abajo)
    def face(cy, mouth):
        c.ell(20, cy, 14, 12, '2')
        c.ell(20, cy, 12, 10, '1')
        c.rect(8, cy - 6, 32, cy - 5, '2')        # ceño
        c.rect(10, cy - 3, 14, cy - 1, '4')        # ojos
        c.rect(20, cy - 3, 24, cy - 1, '4')
        if mouth == 'furia':
            for x in range(10, 26, 3):
                c.rect(x, cy + 4, x + 1, cy + 6, '2')
        elif mouth == 'hambre':
            c.rect(8, cy + 3, 26, cy + 7, '.')
            c.box(8, cy + 3, 26, cy + 7, '2')
        else:
            c.line(10, cy + 5, 26, cy + 3, '2')
        c.set(3, cy - 10, '2'); c.set(4, cy - 9, '2'); c.set(5, cy - 8, '2')  # cuernos
    face(13, 'furia')
    face(40, 'hambre')
    face(67, 'ceniza')
    return c


