BW, BH = 48, 80


def vmirror(c):  # mitad de arriba -> abajo
    for y in range(c.h // 2):
        c.p[c.h - 1 - y] = list(c.p[y])
    return c


def boss_ferrum():
    c = C(BW, BH)
    # anillo de maquinaria
    c.rect(14, 4, 47, 39, '1')
    c.box(14, 4, 47, 39, '3')
    c.box(16, 6, 45, 39, '2')
    for x in range(18, 44, 4):
        c.rect(x, 8, x + 1, 9, '3')
    for y in range(12, 40, 6):
        c.rect(42, y, 43, y + 2, '2')
    # mandíbula telescópica superior (hacia la izquierda)
    c.rect(0, 16, 15, 21, '2')
