def real(b):
    m=int.from_bytes(b[:4],'little');e=b[4]
    if e==0: return 0
    s=-1 if m&0x80000000 else 1; m|=0x80000000
    v=s*m/2**32*2**(e-128)
    return ('%g'%v)
